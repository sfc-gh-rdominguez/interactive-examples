
USE ROLE IA_LAB_RL;
USE WAREHOUSE IA_LAB_IWH;
USE SCHEMA IA_LAB.KAFKA_STREAMING;

-- Does the MV match deduped or raw (all versions) counts? Run after LAST_DEDUP converges.
SELECT 'mv'           AS src, SUM(events) AS total FROM MV_ACTIONS_BY_TENANT_HOUR WHERE tenant_id = 'tenant-0001'
UNION ALL
SELECT 'latest_dedup', COUNT(*) FROM AUDIT_EVENTS DEDUP_OPTION = LATEST_DEDUP WHERE tenant_id = 'tenant-0001'
UNION ALL
SELECT 'latest_all',   COUNT(*) FROM AUDIT_EVENTS DEDUP_OPTION = LATEST_ALL   WHERE tenant_id = 'tenant-0001';

SHOW STORAGE LIFECYCLE POLICIES IN SCHEMA IA_LAB.KAFKA_STREAMING;
DESCRIBE STORAGE LIFECYCLE POLICY EXPIRE_180D;
