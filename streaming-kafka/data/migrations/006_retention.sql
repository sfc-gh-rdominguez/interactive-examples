USE ROLE IA_LAB_RL;
USE WAREHOUSE IA_LAB_WH;
USE SCHEMA IA_LAB.KAFKA_STREAMING;

CREATE STORAGE LIFECYCLE POLICY IF NOT EXISTS EXPIRE_180D
  AS (c TIMESTAMP_NTZ) RETURNS BOOLEAN -> c < DATEADD(DAY, -180, CURRENT_TIMESTAMP());

ALTER TABLE AUDIT_EVENTS ADD STORAGE LIFECYCLE POLICY EXPIRE_180D ON (event_ts);
