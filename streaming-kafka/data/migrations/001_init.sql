USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS IA_LAB_RL;
GRANT ROLE IA_LAB_RL TO ROLE SYSADMIN;

SET grant_stmt = 'GRANT ROLE IA_LAB_RL TO USER "' || CURRENT_USER() || '"';
EXECUTE IMMEDIATE $grant_stmt;

-- The lab role creates and owns both warehouses (including the interactive one)
GRANT CREATE WAREHOUSE ON ACCOUNT TO ROLE IA_LAB_RL;

CREATE DATABASE IF NOT EXISTS IA_LAB;
GRANT OWNERSHIP ON DATABASE IA_LAB TO ROLE IA_LAB_RL COPY CURRENT GRANTS;

USE ROLE IA_LAB_RL;
CREATE SCHEMA IF NOT EXISTS IA_LAB.KAFKA_STREAMING;
CREATE WAREHOUSE IF NOT EXISTS IA_LAB_WH
  WAREHOUSE_SIZE = XSMALL
  AUTO_SUSPEND = 60
  AUTO_RESUME = TRUE
  INITIALLY_SUSPENDED = TRUE;
