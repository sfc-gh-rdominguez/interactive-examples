USE ROLE IA_LAB_RL;
USE WAREHOUSE IA_LAB_WH;
USE SCHEMA IA_LAB.KAFKA_STREAMING;

CREATE INTERACTIVE MATERIALIZED VIEW IF NOT EXISTS MV_ACTIONS_BY_TENANT_HOUR AS
  SELECT tenant_id, DATE_TRUNC('HOUR', event_ts) AS hour, action, COUNT(*) AS events
  FROM AUDIT_EVENTS
  GROUP BY 1, 2, 3;

ALTER WAREHOUSE IA_LAB_IWH ADD TABLES (MV_ACTIONS_BY_TENANT_HOUR, AUDIT_EVENTS);
