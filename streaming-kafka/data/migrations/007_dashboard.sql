USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS IA_DASH_RL;
GRANT ROLE IA_DASH_RL TO ROLE IA_LAB_RL;

CREATE USER IF NOT EXISTS IA_DASH_SVC
  TYPE = SERVICE
  DEFAULT_ROLE = IA_DASH_RL
  DEFAULT_WAREHOUSE = IA_LAB_WH; -- standard wh...turns out IWH can't be default
ALTER USER IA_DASH_SVC SET RSA_PUBLIC_KEY = '__DASH_PUBLIC_KEY__';
GRANT ROLE IA_DASH_RL TO USER IA_DASH_SVC;

USE ROLE IA_LAB_RL;
GRANT USAGE ON DATABASE IA_LAB TO ROLE IA_DASH_RL;
GRANT USAGE ON SCHEMA IA_LAB.KAFKA_STREAMING TO ROLE IA_DASH_RL;
GRANT SELECT ON TABLE IA_LAB.KAFKA_STREAMING.AUDIT_EVENTS TO ROLE IA_DASH_RL;
GRANT SELECT ON ALL MATERIALIZED VIEWS IN SCHEMA IA_LAB.KAFKA_STREAMING TO ROLE IA_DASH_RL;
GRANT USAGE ON WAREHOUSE IA_LAB_IWH TO ROLE IA_DASH_RL;
GRANT USAGE ON WAREHOUSE IA_LAB_WH  TO ROLE IA_DASH_RL;

ALTER WAREHOUSE IA_LAB_IWH SET FALLBACK_WAREHOUSE = IA_LAB_WH;
